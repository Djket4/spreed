const media = (p) => generateFilePath('spreed', 'img', 'k4stk/' + p)

/** id -> { k: 'g'|'s', id, w, h, tx, src, pos (gif) | th (sticker), pack } */
export const ITEMS = {}
GIFS.forEach(([id, w, h, tx]) => {
	ITEMS[id] = { k: 'g', id, w, h, tx, src: media(id + '.mp4'), pos: media(id + '.jpg') }
})
PACKS.forEach((pack) => pack.s.forEach(([id, w, h, tx]) => {
	ITEMS[id] = { k: 's', id, w, h, tx, src: media(id + '.webp'), th: media(id.replace(/(\d+)$/, '$1s') + '.webp'), pack }
}))

/**
 * Проверка на границе доверия: id из сети должен быть в каталоге и совпадать по виду.
 *
 * @param k
 * @param id
 */
export const find = (k, id) => (typeof id === 'string' && Object.hasOwn(ITEMS, id) && ITEMS[id].k === k ? ITEMS[id] : null)

// ── поиск: эмодзи напрямую или слово -> его эмодзи (как в прототипе) ──
const nz = (x) => x.replace(/️/g, '').toLowerCase()
const WORDS = {
	злюсь: '😡😠😤😾👺',
	класс: '👍😎✔💪👉🤘',
	привет: '👋☀😘',
	смех: '😂😆😁😃😄😅😜',
	грусть: '😢😭😔😞😿😩',
	шок: '😱😲😳😵',
	любовь: '😍💋😘',
	ура: '🎉🥂👏',
	думаю: '🤔',
	нет: '👎',
	ок: '👍👌✔',
	кот: '🐱😾😿',
	устал: '😴😩😵',
	деньги: '💵💸',
}
/**
 * @param {string} q запрос
 * @param {string} tx теги/эмодзи элемента
 */
export function hit(q, tx) {
	q = nz(q)
	if (!q) {
		return true
	}
	tx = nz(tx)
	if (tx.includes(q)) {
		return true
	}
	return Object.entries(WORDS).some(([w, e]) => (w.startsWith(q) || nz(e).includes(q)) && [...nz(e)].some((c) => tx.includes(c)))
}

/** Быстрые эмодзи-фильтры: для гифок фиксированные, для стикеров — самые частые. */
export const CHIPS_GIF = [...'😂🎉👏🥂😱😢🐱🤔🔥💵😴🤗']
export const CHIPS_STK = (() => {
	const c = {}
	const raw = {}
	PACKS.forEach((p) => p.s.forEach(([, , , e]) => {
		const n = nz(e)
		c[n] = (c[n] || 0) + 1
		raw[n] = n.length < 2 && n.codePointAt(0) < 0x2800 ? n + '️' : e
	}))
	return Object.keys(c).sort((a, b) => c[b] - c[a]).slice(0, 12).map((e) => raw[e])
})()
