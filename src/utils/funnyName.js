/**
 * ket4tec: «Придумать имя» для гостя — прилагательное + зверь, род согласован.
 * Списки правятся по вкусу владельца.
 */
const ADJ = [
	['Весёлый', 'Весёлая'],
	['Сонный', 'Сонная'],
	['Хитрый', 'Хитрая'],
	['Задумчивый', 'Задумчивая'],
	['Космический', 'Космическая'],
	['Бодрый', 'Бодрая'],
	['Пушистый', 'Пушистая'],
	['Деловой', 'Деловая'],
	['Загадочный', 'Загадочная'],
	['Стремительный', 'Стремительная'],
	['Ленивый', 'Ленивая'],
	['Танцующий', 'Танцующая'],
	['Отважный', 'Отважная'],
	['Невозмутимый', 'Невозмутимая'],
	['Поющий', 'Поющая'],
	['Креативный', 'Креативная'],
]
const ANIMALS = [
	['Енот', 0],
	['Барсук', 0],
	['Пингвин', 0],
	['Ёж', 0],
	['Кот', 0],
	['Хомяк', 0],
	['Лось', 0],
	['Бобр', 0],
	['Капибара', 1],
	['Лиса', 1],
	['Сова', 1],
	['Панда', 1],
	['Альпака', 1],
	['Выдра', 1],
	['Белка', 1],
	['Черепаха', 1],
]

const pick = (list) => list[Math.floor(Math.random() * list.length)]

/**
 * @return {string} random funny guest name, e.g. «Сонная Капибара»
 */
export function funnyName() {
	const [animal, feminine] = pick(ANIMALS)
	return `${pick(ADJ)[feminine]} ${animal}`
}
